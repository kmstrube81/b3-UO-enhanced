CREATE TABLE IF NOT EXISTS pamx_teams (
id INTEGER PRIMARY KEY AUTOINCREMENT,
name VARCHAR(32) NOT NULL COLLATE NOCASE UNIQUE,
wins INTEGER(10) NOT NULL DEFAULT 0,
losses INTEGER(10) NOT NULL DEFAULT 0,
draws INTEGER(10) NOT NULL DEFAULT 0,
time_add INTEGER(10) NOT NULL DEFAULT 0,
time_edit INTEGER(10) NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS pamx_team_players (
id INTEGER PRIMARY KEY AUTOINCREMENT,
team_id INTEGER(10) NOT NULL,
client_id INTEGER(10) NOT NULL,
time_add INTEGER(10) NOT NULL DEFAULT 0,
UNIQUE (team_id, client_id));

CREATE TABLE IF NOT EXISTS pamx_active_match (
id INTEGER PRIMARY KEY,
team1_id INTEGER(10) NOT NULL,
team2_id INTEGER(10) NOT NULL,
time_add INTEGER(10) NOT NULL DEFAULT 0);
