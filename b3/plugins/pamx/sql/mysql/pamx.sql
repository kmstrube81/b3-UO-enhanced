CREATE TABLE IF NOT EXISTS pamx_teams (
id INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,
name VARCHAR(32) NOT NULL,
wins INT(10) UNSIGNED NOT NULL DEFAULT 0,
losses INT(10) UNSIGNED NOT NULL DEFAULT 0,
draws INT(10) UNSIGNED NOT NULL DEFAULT 0,
time_add INT(10) UNSIGNED NOT NULL DEFAULT 0,
time_edit INT(10) UNSIGNED NOT NULL DEFAULT 0,
PRIMARY KEY (id),
UNIQUE KEY name (name)
) ENGINE=MyISAM DEFAULT CHARSET=utf8 COLLATE=utf8_general_ci AUTO_INCREMENT=1;

CREATE TABLE IF NOT EXISTS pamx_team_players (
id INT(10) UNSIGNED NOT NULL AUTO_INCREMENT,
team_id INT(10) UNSIGNED NOT NULL,
client_id INT(10) UNSIGNED NOT NULL,
time_add INT(10) UNSIGNED NOT NULL DEFAULT 0,
PRIMARY KEY (id),
UNIQUE KEY team_client (team_id, client_id),
KEY client_id (client_id)
) ENGINE=MyISAM DEFAULT CHARSET=utf8 AUTO_INCREMENT=1;

CREATE TABLE IF NOT EXISTS pamx_active_match (
id INT(10) UNSIGNED NOT NULL,
team1_id INT(10) UNSIGNED NOT NULL,
team2_id INT(10) UNSIGNED NOT NULL,
time_add INT(10) UNSIGNED NOT NULL DEFAULT 0,
PRIMARY KEY (id)
) ENGINE=MyISAM DEFAULT CHARSET=utf8;
