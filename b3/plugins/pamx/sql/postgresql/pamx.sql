CREATE TABLE IF NOT EXISTS pamx_teams (
id SERIAL PRIMARY KEY,
name VARCHAR(32) NOT NULL,
wins INTEGER NOT NULL DEFAULT 0,
losses INTEGER NOT NULL DEFAULT 0,
draws INTEGER NOT NULL DEFAULT 0,
time_add INTEGER NOT NULL DEFAULT 0,
time_edit INTEGER NOT NULL DEFAULT 0);

CREATE UNIQUE INDEX IF NOT EXISTS pamx_teams_name_lower ON pamx_teams (LOWER(name));

CREATE TABLE IF NOT EXISTS pamx_team_players (
id SERIAL PRIMARY KEY,
team_id INTEGER NOT NULL,
client_id INTEGER NOT NULL,
time_add INTEGER NOT NULL DEFAULT 0,
UNIQUE (team_id, client_id));

CREATE TABLE IF NOT EXISTS pamx_active_match (
id INTEGER PRIMARY KEY,
team1_id INTEGER NOT NULL,
team2_id INTEGER NOT NULL,
time_add INTEGER NOT NULL DEFAULT 0);
